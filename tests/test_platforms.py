@respx.mock
async def test_github_fetch_issue_and_pr(gh) -> None:
    respx.get(f"{GH}/repos/psf/requests/issues").mock(
        return_value=httpx.Response(
            200,
            json=[
                {
                    "number": 1, "title": "崩溃", "body": "boom", "state": "open",
                    "labels": [{"name": "bug"}], "user": {"login": "reporter"},
                    "created_at": "2026-01-01T00:00:00Z", "updated_at": "2026-01-02T00:00:00Z",
                    "html_url": "https://github.com/psf/requests/issues/1",
                },
                {
                    "number": 2, "title": "修复崩溃", "body": "closes #1", "state": "open",
                    "labels": [], "user": {"login": "dev"},
                    "created_at": "2026-01-03T00:00:00Z", "updated_at": "2026-01-04T00:00:00Z",
                    "pull_request": {"url": "https://api.github.com/..."},
                },
            ],
        )
    )
    respx.get(f"{GH}/repos/psf/requests/issues/1/comments").mock(
        return_value=httpx.Response(200, json=[
            {"user": {"login": "u2"}, "body": "me too", "created_at": "2026-01-02T01:00:00Z"}
        ])
    )
    respx.get(f"{GH}/repos/psf/requests/issues/2/comments").mock(return_value=httpx.Response(200, json=[]))
    respx.get(f"{GH}/repos/psf/requests/pulls/2").mock(
        return_value=httpx.Response(200, json={
            "base": {"ref": "main"}, "head": {"ref": "fix", "repo": {"full_name": "dev/requests"}},
            "merged_at": None, "mergeable": True, "draft": False,
            "additions": 5, "deletions": 1, "changed_files": 1, "title": "修复崩溃", "body": "closes #1",
        })
    )

    items = [i async for i in gh.fetch_items(REPO, item_types=[ItemType.ISSUE, ItemType.PR])]
    assert len(items) == 2

    issue = items[0]
    assert issue.number == 1 and issue.item_type is ItemType.ISSUE
    assert issue.labels == ["bug"] and issue.author == "reporter"
    assert len(issue.comments) == 1 and issue.comments[0].body == "me too"

    pr = items[1]
    assert pr.item_type is ItemType.PR
    assert pr.base_branch == "main" and pr.head_branch == "fix"
    assert pr.head_repo == "dev/requests"
    assert pr.additions == 5 and pr.changed_files == 1
    assert pr.linked_issues == [1]


