@pytest.mark.parametrize(
    "value,expected_year",
    [("2026-01-02T03:04:05Z", 2026), ("2026-01-02T03:04:05+00:00", 2026),
     ("2026-01-02 03:04:05", 2026), ("2026-01-02", 2026), ("", None), (None, None),
     ("garbage", None)],
)
def test_parse_dt(value, expected_year) -> None:
    dt = parse_dt(value)
    if expected_year is None:
        assert dt is None
    else:
        assert dt is not None and dt.year == expected_year


def test_guess_author_kind() -> None:
    assert guess_author_kind("dependabot[bot]") is AuthorKind.BOT
    assert guess_author_kind("someone", labels=["ai-generated"]) is AuthorKind.AI_AGENT
    assert guess_author_kind("dev", maintainers=["dev"]) is AuthorKind.MAINTAINER
    assert guess_author_kind("random") is AuthorKind.COMMUNITY
    assert guess_author_kind("") is AuthorKind.UNKNOWN
    assert guess_author_kind("x", body="Generated by Copilot") is AuthorKind.AI_AGENT


def test_extract_linked_issues() -> None:
    assert extract_linked_issues("fixes #42 and #43") == [42, 43]
    assert extract_linked_issues("see /issues/7") == [7]
    assert extract_linked_issues("closes /merge_requests/9") == [9]
    assert extract_linked_issues("nothing here") == []
    assert extract_linked_issues("#5 and #5") == [5]


def test_parse_repo_ref_variants() -> None:
    assert parse_repo_ref("a/b", Platform.GITHUB).slug == "a/b"
    assert parse_repo_ref("gitee:a/b").platform is Platform.GITEE
    assert parse_repo_ref("atomgit:o/n").platform is Platform.ATOMGIT
    with pytest.raises(Exception):
        parse_repo_ref("invalid")


def test_registry_build_and_urls(settings) -> None:
    for plat, cls in ADAPTERS.items():
        a = build_adapter(settings, platform=plat, token="tok")
        assert isinstance(a, cls)
        assert a.item_url(RepoRef(platform=plat, owner="o", name="n"), 3, ItemType.PR).startswith("https://")
        assert "***" in a.sanitize(a.clone_url(RepoRef(platform=plat, owner="o", name="n"), use_token=True))
    assert get_adapter_class(Platform.GITLAB) is GitLabAdapter


def test_resolve_repos_from_config_and_spec(settings) -> None:
    assert [r.slug for r in resolve_repos(settings, None)] == ["psf/requests"]
    assert [r.slug for r in resolve_repos(settings, ["psf/requests"])] == ["psf/requests"]
    # 未登记 → 临时构造
    out = resolve_repos(settings, ["gitee:other/repo"])
    assert out[0].slug == "other/repo" and out[0].platform is Platform.GITEE


