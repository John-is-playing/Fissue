@respx.mock
async def test_gitlab_fetch_issue_and_mr(gl) -> None:
    pid = "psf%2Frequests"
    respx.get(f"{GL}/projects/{pid}/issues").mock(
        return_value=httpx.Response(200, json=[{
            "iid": 5, "title": "bug", "description": "desc", "state": "opened",
            "labels": ["bug"], "author": {"username": "u"}, "created_at": "2026-03-01T00:00:00Z",
            "web_url": "https://gitlab.com/psf/requests/-/issues/5",
        }])
    )
    respx.get(f"{GL}/projects/{pid}/issues/5/notes").mock(
        return_value=httpx.Response(200, json=[
            {"body": "系统事件", "system": True, "author": {"username": "bot"}},
            {"body": "我来看看", "system": False, "author": {"username": "m"}},
        ])
    )
    respx.get(f"{GL}/projects/{pid}/merge_requests").mock(
        return_value=httpx.Response(200, json=[{
            "iid": 6, "title": "mr", "description": "closes #5", "state": "opened",
            "labels": [], "author": {"username": "d"}, "target_branch": "main",
            "source_branch": "fix", "merge_status": "can_be_merged",
        }])
    )
    respx.get(f"{GL}/projects/{pid}/merge_requests/6/changes").mock(
        return_value=httpx.Response(200, json={
            "additions": 7, "deletions": 2,
            "changes": [{"old_path": "a.py", "new_path": "a.py", "diff": "@@ -1 +1 @@\n-x\n+y\n"}],
        })
    )
    respx.get(f"{GL}/projects/{pid}/merge_requests/6/notes").mock(return_value=httpx.Response(200, json=[]))

    items = [i async for i in gl.fetch_items(REPO, item_types=[ItemType.ISSUE, ItemType.PR])]
    assert len(items) == 2

    issue = [i for i in items if i.item_type is ItemType.ISSUE][0]
    assert issue.number == 5 and issue.state == "open"
    assert len(issue.comments) == 1                  # system 事件被过滤
    assert issue.comments[0].body == "我来看看"

    mr = [i for i in items if i.item_type is ItemType.PR][0]
    assert mr.base_branch == "main" and mr.head_branch == "fix"
    assert mr.additions == 7 and mr.changed_files == 1
    assert mr.linked_issues == [5]


