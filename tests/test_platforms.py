@pytest.mark.parametrize(
    "value,expected_year",
    [("2026-01-02T03:04:05Z", 2026), ("2026-01-02T03:04:05+00:00", 2026),
     ("2026-01-02 03:04:05", 2026), ("2026-01-02", 2026), ("", None), (None, None),
     ("garbage", None)],
)
def test_parse_dt(value, expected_year) -> None:
    dt = parse_dt(value)
    if expected_year is None:
        assert dt is None
    else:
        assert dt is not None and dt.year == expected_year


