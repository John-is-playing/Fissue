@respx.mock
async def test_label_cache_expires_after_ttl(gh, monkeypatch) -> None:
    """超过 TTL 后重新拉取（时间打桩，不真等）。"""
    labels = respx.get(f"{GH}/repos/psf/requests/labels").mock(
        return_value=httpx.Response(200, json=[{"name": "bug"}])
    )
